def flores_to_bcp47(flores_code: str) -> str | None:
    """Convert a FLORES-200 code to a BCP-47 tag for Windows OCR."""
    return FLORES_TO_BCP47.get(flores_code)


def get_flores_code(language_name: str) -> str | None:
    """Get FLORES-200 code for a language display name."""
    return FLORES_CODES.get(language_name)


def get_language_name(flores_code: str) -> str:
    """Get display name for a FLORES-200 code."""
    return CODE_TO_NAME.get(flores_code, flores_code)


def get_all_languages() -> list[str]:
    """Return sorted list of all language display names, with common ones first."""
    common = [l for l in COMMON_LANGUAGES if l in FLORES_CODES]
    others = sorted(set(FLORES_CODES.keys()) - set(COMMON_LANGUAGES))
    return common + others
